"""Sanity-check training ladder for the new synthetic `recovery_outcome`
dataset (data/recoverchain/synthetic/recovery_outcome/). This is a genuine
recovery target (see docs/ai_reconstruction/02_SEMANTIC_TARGET_CLASSIFICATION.md)
generated by scripts/data_generation/generate_recoverchain_datasets.py.

Purpose: verify the dataset is honestly learnable -- neither trivial
(near-1.0 ROC-AUC from leakage) nor unlearnable (near-0.5, random) -- before
treating it as usable. Same baseline-ladder pattern as train_ar_recovery.py.

Usage:
    venv/Scripts/python.exe ml_reconstruction/train_recovery_outcome.py
"""

import json
import time
from pathlib import Path

import numpy as np
import pandas as pd
from sklearn.calibration import CalibratedClassifierCV
from sklearn.compose import ColumnTransformer
from sklearn.ensemble import RandomForestClassifier
from sklearn.frozen import FrozenEstimator
from sklearn.impute import SimpleImputer
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import (
    accuracy_score,
    average_precision_score,
    brier_score_loss,
    confusion_matrix,
    f1_score,
    log_loss,
    precision_score,
    recall_score,
    roc_auc_score,
)
from sklearn.pipeline import Pipeline
from sklearn.preprocessing import OneHotEncoder, StandardScaler
from xgboost import XGBClassifier

HERE = Path(__file__).resolve().parent
DATA_PATH = (
    HERE.parent.parent
    / "data"
    / "recoverchain"
    / "synthetic"
    / "recovery_outcome"
    / "recovery_outcome.csv"
)
OUT_DIR = HERE / "runs"
OUT_DIR.mkdir(parents=True, exist_ok=True)

TARGET = "recovery_success"
CATEGORICAL = [
    "domain",
    "payment_method",
    "account_status",
    "consent_status",
    "historical_recovery_behavior",
]
NUMERIC = [
    "amount_at_risk",
    "age_of_obligation",
    "customer_tenure",
    "prior_payment_success_rate",
    "prior_recovery_rate",
    "prior_late_rate",
    "number_of_previous_failed_attempts",
    "number_of_previous_recoveries",
    "average_days_to_payment",
    "amount_vs_customer_average",
    "invoice_age",
    "payment_method_valid",
    "customer_engagement",
    "recent_login",
    "reminder_history",
    "previous_contact_success",
    "dispute_indicator",
    "suppression_status",
]
FEATURES = NUMERIC + CATEGORICAL
# Deliberately excluded: case_id, customer_id, obligation_id (identifiers),
# obligation_created_at (used only for the split), split itself.


def _metrics(y_true, y_prob, threshold=0.5) -> dict:
    y_pred = (y_prob >= threshold).astype(int)
    cm = confusion_matrix(y_true, y_pred)
    tn, fp, fn, tp = cm.ravel() if cm.size == 4 else (0, 0, 0, 0)
    out = {
        "accuracy": float(accuracy_score(y_true, y_pred)),
        "precision": float(precision_score(y_true, y_pred, zero_division=0)),
        "recall": float(recall_score(y_true, y_pred, zero_division=0)),
        "f1": float(f1_score(y_true, y_pred, zero_division=0)),
        "confusion_matrix": {"tn": int(tn), "fp": int(fp), "fn": int(fn), "tp": int(tp)},
        "positive_rate": float(np.mean(y_true)),
    }
    if len(np.unique(y_true)) > 1:
        out["roc_auc"] = float(roc_auc_score(y_true, y_prob))
        out["pr_auc"] = float(average_precision_score(y_true, y_prob))
        out["brier_score"] = float(brier_score_loss(y_true, y_prob))
        out["log_loss"] = float(log_loss(y_true, np.clip(y_prob, 1e-6, 1 - 1e-6)))
    return out


def main():
    df = pd.read_csv(DATA_PATH)
    df["suppression_status"] = df["suppression_status"].astype(int)

    tr = df[df["split"] == "train"]
    va = df[df["split"] == "validation"]
    te = df[df["split"] == "test"]
    print(f"train={len(tr)} validation={len(va)} test={len(te)}")
    print(f"train positive rate={tr[TARGET].mean():.4f}")

    X_tr, y_tr = tr[FEATURES], tr[TARGET].to_numpy()
    X_va, y_va = va[FEATURES], va[TARGET].to_numpy()
    X_te, y_te = te[FEATURES], te[TARGET].to_numpy()

    results = {}
    majority = int(round(y_tr.mean()))
    results["baseline_0_majority"] = {
        "test_metrics": _metrics(y_te, np.full(len(y_te), float(majority)))
    }

    hist = te["prior_recovery_rate"].replace(-1, y_tr.mean()).clip(0, 1).to_numpy()
    results["baseline_1_historical_rate"] = {"test_metrics": _metrics(y_te, hist)}

    pre = ColumnTransformer(
        [
            (
                "num",
                Pipeline(
                    [("impute", SimpleImputer(strategy="median")), ("scale", StandardScaler())]
                ),
                NUMERIC,
            ),
            ("cat", OneHotEncoder(handle_unknown="ignore"), CATEGORICAL),
        ]
    )
    candidates = {
        "logistic_regression": LogisticRegression(
            class_weight="balanced", max_iter=1000, random_state=42
        ),
        "random_forest": RandomForestClassifier(
            n_estimators=300,
            max_depth=7,
            min_samples_leaf=8,
            class_weight="balanced",
            random_state=42,
            n_jobs=-1,
        ),
        "xgboost": XGBClassifier(
            n_estimators=300,
            max_depth=4,
            learning_rate=0.05,
            scale_pos_weight=(y_tr == 0).sum() / max(1, (y_tr == 1).sum()),
            eval_metric="logloss",
            random_state=42,
            use_label_encoder=False,
        ),
    }
    for name, clf in candidates.items():
        t0 = time.time()
        pipe = Pipeline([("pre", pre), ("clf", clf)])
        pipe.fit(X_tr, y_tr)
        try:
            model = CalibratedClassifierCV(FrozenEstimator(pipe), method="sigmoid")
            model.fit(X_va, y_va)
            calibrated_ok = True
        except Exception as e:
            model = pipe
            calibrated_ok = False
            print(f"  [{name}] calibration skipped: {e}")
        p_va = model.predict_proba(X_va)[:, 1]
        p_te = model.predict_proba(X_te)[:, 1]
        results[name] = {
            "calibrated": calibrated_ok,
            "training_time_sec": round(time.time() - t0, 3),
            "validation_metrics": _metrics(y_va, p_va),
            "test_metrics": _metrics(y_te, p_te),
        }

    ranked = sorted(
        (
            (n, r["validation_metrics"]["pr_auc"])
            for n, r in results.items()
            if "validation_metrics" in r
        ),
        key=lambda x: x[1],
        reverse=True,
    )
    results["_selection"] = {
        "criterion": "validation PR-AUC",
        "ranked": ranked,
        "selected_model": ranked[0][0],
    }

    print(json.dumps({k: v for k, v in results.items() if k != "_selection"}, indent=2))
    print(json.dumps(results["_selection"], indent=2))

    out_path = OUT_DIR / f"recovery_outcome_{int(time.time())}.json"
    with open(out_path, "w") as f:
        json.dump(
            {
                "dataset": "recovery_outcome (synthetic)",
                "features": FEATURES,
                "target": TARGET,
                "results": results,
            },
            f,
            indent=2,
        )
    print(f"\nSaved: {out_path}")


if __name__ == "__main__":
    main()
