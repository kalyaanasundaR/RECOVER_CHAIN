"""Phase 16 - trace identity and output redaction (dependency-free).

TRACE IDENTITY. One recovery journey == one case, so the journey's `trace_id` is a
pure function of the case id: `trace_id_for_case("case_ab12") == "trace_ab12"`. It is
therefore immutable by construction - it is never stored somewhere it could drift, it
cannot be regenerated by a retry, a re-advance, a page reload, an approval or a
repeated verification, and every stage (agent, policy, approval, execution, outcome)
derives the *same* value independently. What varies per operation - an agent run, an
execution attempt - is a separate `operation_id`; the trace they belong to is carried
as `trace_id` (a child operation's parent).

Trade-off, stated plainly: a derived id can never be "re-assigned", which is the point,
but it also means the trace is only as unique as the case id, and pre-Phase-16 audit
records (which carry random per-run ids from Phase 15) are reported as LEGACY by the
validator rather than rewritten.
"""

from __future__ import annotations

import re
import uuid

TRACE_PREFIX = "trace_"
_CASE_PREFIX = "case_"


def trace_id_for_case(case_id: str) -> str:
    rest = case_id[len(_CASE_PREFIX) :] if case_id.startswith(_CASE_PREFIX) else case_id
    return f"{TRACE_PREFIX}{rest}"


def case_id_candidates_for_trace(trace_id: str) -> list[str]:
    """Inverse of trace_id_for_case. Two candidates because ids without the `case_`
    prefix map to the bare remainder; the caller checks which one exists."""
    if not isinstance(trace_id, str) or not trace_id.startswith(TRACE_PREFIX):
        return []
    rest = trace_id[len(TRACE_PREFIX) :]
    return [f"{_CASE_PREFIX}{rest}", rest] if rest else []


def is_trace_id(value: object) -> bool:
    return (
        isinstance(value, str) and value.startswith(TRACE_PREFIX) and len(value) > len(TRACE_PREFIX)
    )


def new_operation_id(kind: str = "op") -> str:
    return f"{kind}_{uuid.uuid4().hex[:12]}"


# ---------------------------------------------------------------- redaction

_SECRET_KEY = re.compile(
    r"(api[_-]?key|secret|token|passw(or)?d|authorization|credential|private[_-]?key|"
    r"card[_-]?(number|no)|cvv|cvc|iban|account[_-]?number|routing[_-]?number|bearer)",
    re.IGNORECASE,
)
_PAN = re.compile(r"\b(?:\d[ -]?){13,19}\b")
_BEARER = re.compile(r"(?i)bearer\s+[A-Za-z0-9._\-]+")
_KEYLIKE = re.compile(r"\b(?:sk-|AIza|xox[abp]-|ghp_)[A-Za-z0-9_\-]{12,}")
_EMAIL = re.compile(r"[A-Za-z0-9._%+\-]+@([A-Za-z0-9\-]+\.)+[A-Za-z]{2,}")

REDACTED = "[REDACTED]"


def redact_text(text: str) -> str:
    text = _BEARER.sub("Bearer [REDACTED]", text)
    text = _KEYLIKE.sub("[REDACTED_KEY]", text)
    text = _PAN.sub("[REDACTED_PAN]", text)
    return _EMAIL.sub("[EMAIL]", text)


def mask_identifier(value):
    """Customer ids are kept (needed for debugging) unless they are themselves an email."""
    if isinstance(value, str) and "@" in value:
        local, _, domain = value.partition("@")
        return f"{local[:1]}***@{domain}"
    return value


def redact(obj):
    """Recursively redact a JSON-like structure: secret-named keys are replaced
    wholesale; string values are scrubbed for card numbers, bearer tokens, API-key
    shapes and emails. Structure and non-sensitive diagnostics are preserved."""
    if isinstance(obj, dict):
        out = {}
        for k, v in obj.items():
            if isinstance(k, str) and _SECRET_KEY.search(k):
                out[k] = REDACTED
            else:
                out[k] = redact(v)
        return out
    if isinstance(obj, (list, tuple)):
        return [redact(v) for v in obj]
    if isinstance(obj, str):
        return redact_text(obj)
    return obj
