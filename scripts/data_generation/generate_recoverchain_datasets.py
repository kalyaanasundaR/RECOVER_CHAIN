def _sigmoid(z):
    return 1.0 / (1.0 + np.exp(-z))


def _checksum(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


# ---------------------------------------------------------------------------
# Dataset 1: Recovery Outcome — a genuine recovery target
# ---------------------------------------------------------------------------

N_RECOVERY = 6000
OBSERVATION_WINDOW_DAYS = 30

DOMAINS = [
    "FAILED_PAYMENT",
    "CHECKOUT_ABANDONMENT",
    "FAILED_SUBSCRIPTION",
    "OVERDUE_INVOICE",
    "BROKEN_PROMISE",
]
PAYMENT_METHODS = ["card", "bank_transfer", "wallet", "upi", "unknown"]
ACCOUNT_STATUSES = [
    "active",
    "active",
    "active",
    "dormant",
    "closed",
]  # weighted toward active


def generate_recovery_outcome(n=N_RECOVERY, seed=SEED):
    """Repaired generation mechanism (found and fixed during model-lineage
    reconciliation — see docs/ai_reconstruction/RECOVERY_DATASET_VALIDATION.md):
    the original version drew `prior_recovery_rate` and
    `number_of_previous_recoveries`/`_failed_attempts` as INDEPENDENT random
    values per row, so the same customer's own count of previous recoveries
    could go DOWN across their later obligations -- a logical impossibility
    for a true cumulative statistic, and a real (if subtle) form of temporal
    leakage: a "prior" feature that isn't actually computed from what came
    before it.

    This version builds each customer's obligations SEQUENTIALLY in time and
    computes `prior_recovery_rate` / `number_of_previous_recoveries` /
    `number_of_previous_failed_attempts` as genuine ROLLING statistics over
    that customer's own earlier obligations' OWN recovery_success outcomes
    -- exactly ar_recovery_v1's own documented methodology ("Constructed
    temporal history features using strictly prior invoices"), applied here
    for the first time to this dataset.

    `prior_payment_success_rate` and `prior_late_rate` remain customer-level
    traits fixed at account-open time (a payment-success reputation from
    BEFORE this dataset's own observation window begins) -- legitimately
    static, not leakage, and documented as such in the manifest.
    """
    rng = np.random.default_rng(seed)
    n_customers = max(200, n // 6)

    # Per-customer latent "reliability" -- still drives correlated traits, but
    # no longer drives the rolling recovery-history features directly; those
    # now come from genuine sequential simulation below.
    customer_reliability = rng.beta(2.5, 2.5, size=n_customers)
    customer_tenure_pool = rng.integers(1, 2000, size=n_customers)
    customer_avg_amount_pool = np.exp(rng.normal(6.3, 0.9, size=n_customers))
    # Fixed, pre-dataset traits (legitimately static -- see docstring above).
    customer_prior_payment_success = np.clip(rng.normal(customer_reliability, 0.15), 0, 1)
    customer_prior_late_rate = np.clip(rng.normal(1 - customer_reliability, 0.15), 0, 1)

    start = datetime(2024, 1, 1, tzinfo=UTC)
    window_days = 700
    domain_p = [0.40, 0.15, 0.15, 0.20, 0.10]
    domain_effect_map = {
        "FAILED_PAYMENT": 0.35,
        "CHECKOUT_ABANDONMENT": -0.10,
        "FAILED_SUBSCRIPTION": 0.10,
        "OVERDUE_INVOICE": 0.05,
        "BROKEN_PROMISE": -0.25,
    }

    # How many obligations each customer has, then their obligation dates,
    # generated up front and sorted so each customer's own sequence is truly
    # chronological.
    n_obligations = rng.poisson(lam=max(2, n / n_customers), size=n_customers).clip(1, 20)
    total_rows = int(n_obligations.sum())

    rows = []
    row_i = 0
    for cust_i in range(n_customers):
        k = int(n_obligations[cust_i])
        if k == 0:
            continue
        reliability = customer_reliability[cust_i]
        dates = np.sort(rng.integers(0, window_days, size=k))
        recoveries_so_far = 0
        non_recoveries_so_far = 0

        for day in dates:
            total_so_far = recoveries_so_far + non_recoveries_so_far
            prior_recovery_rate = recoveries_so_far / total_so_far if total_so_far > 0 else -1.0

            domain = rng.choice(DOMAINS, p=domain_p)
            amount_at_risk = float(np.clip(np.round(np.exp(rng.normal(6.5, 1.1)), 2), 20, 250000))
            age_of_obligation = int(rng.integers(0, 180))
            avg_amt = customer_avg_amount_pool[cust_i]
            amount_vs_customer_average = amount_at_risk / max(avg_amt, 1)
            invoice_age = age_of_obligation + int(rng.integers(0, 15))
            payment_method = rng.choice(PAYMENT_METHODS, p=[0.45, 0.20, 0.15, 0.15, 0.05])
            payment_method_valid = int(rng.binomial(1, float(np.clip(reliability + 0.3, 0, 0.98))))
            customer_engagement = float(np.clip(rng.normal(reliability, 0.2), 0, 1))
            recent_login = int(rng.binomial(1, customer_engagement))
            reminder_history = int(rng.poisson(lam=2.0))
            previous_contact_success = float(np.clip(rng.normal(reliability * 0.7, 0.2), 0, 1))
            dispute_indicator = int(
                rng.binomial(1, float(np.clip(0.08 - 0.05 * reliability, 0.01, 0.15)))
            )
            account_status = rng.choice(ACCOUNT_STATUSES)
            consent_status = rng.choice(["ALLOWED", "ALLOWED", "ALLOWED", "OPTED_OUT", "UNKNOWN"])
            suppression_status = bool(rng.choice([False, False, False, False, True]))
            average_days_to_payment = float(
                np.clip(rng.normal(30 * (1 - reliability) + 3, 8), 0, 120)
            )

            hrb_score = reliability + rng.normal(0, 0.1)
            historical_recovery_behavior = (
                "consistently_recovers"
                if hrb_score > 0.6
                else ("mixed" if hrb_score > 0.3 else "rarely_recovers")
            )

            amount_z = (
                np.log(amount_at_risk) - 6.5
            ) / 1.1  # standardized vs. the generating distribution
            z = (
                -0.2
                + 2.1 * (max(prior_recovery_rate, 0) - 0.5 if prior_recovery_rate >= 0 else 0.0)
                + 1.1 * (customer_prior_payment_success[cust_i] - 0.5)
                - 1.3 * customer_prior_late_rate[cust_i]
                - 0.18 * non_recoveries_so_far
                + 0.22 * recoveries_so_far
                - 0.45 * amount_z
                - 0.010 * age_of_obligation
                + 0.9 * (customer_engagement - 0.5)
                + 0.5 * recent_login
                + 0.8 * (previous_contact_success - 0.5)
                - 1.4 * dispute_indicator
                - 1.1 * (1 - payment_method_valid)
                - 1.6 * (1.0 if consent_status == "OPTED_OUT" else 0.0)
                - 1.8 * (1.0 if suppression_status else 0.0)
                + domain_effect_map[domain]
                + rng.normal(0, 0.9)
            )
            p_recovery = float(_sigmoid(z))
            recovery_success = int(rng.binomial(1, p_recovery))

            rows.append(
                {
                    "case_id": f"syn_case_{row_i:06d}",
                    "customer_id": f"cust_{cust_i:05d}",
                    "obligation_id": f"syn_ob_{row_i:06d}",
                    "domain": domain,
                    "obligation_created_at": start + timedelta(days=int(day)),
                    "amount_at_risk": amount_at_risk,
                    "age_of_obligation": age_of_obligation,
                    "customer_tenure": int(customer_tenure_pool[cust_i]),
                    "prior_payment_success_rate": round(
                        float(customer_prior_payment_success[cust_i]), 4
                    ),
                    "prior_recovery_rate": round(prior_recovery_rate, 4),
                    "prior_late_rate": round(float(customer_prior_late_rate[cust_i]), 4),
                    "number_of_previous_failed_attempts": non_recoveries_so_far,
                    "number_of_previous_recoveries": recoveries_so_far,
                    "average_days_to_payment": round(average_days_to_payment, 2),
                    "amount_vs_customer_average": round(amount_vs_customer_average, 4),
                    "invoice_age": invoice_age,
                    "payment_method": payment_method,
                    "payment_method_valid": payment_method_valid,
                    "customer_engagement": round(customer_engagement, 4),
                    "recent_login": recent_login,
                    "reminder_history": reminder_history,
                    "previous_contact_success": round(previous_contact_success, 4),
                    "dispute_indicator": dispute_indicator,
                    "account_status": account_status,
                    "consent_status": consent_status,
                    "suppression_status": suppression_status,
                    "historical_recovery_behavior": historical_recovery_behavior,
                    "recovery_success": recovery_success,
                }
            )
            row_i += 1

            # Update the running history AFTER this obligation's own label is
            # decided, so it only ever informs LATER obligations of the same
            # customer -- never itself, never an earlier one.
            if recovery_success:
                recoveries_so_far += 1
            else:
                non_recoveries_so_far += 1

    df = pd.DataFrame(rows)
    assert len(df) == total_rows

    # A handful of genuinely missing values (not the -1 sentinel — real gaps) in a
    # low-stakes field, so the pipeline is honestly exercised on missing data too.
    rng2 = np.random.default_rng(seed + 100)
    miss_idx = rng2.choice(len(df), size=int(len(df) * 0.02), replace=False)
    df.loc[miss_idx, "average_days_to_payment"] = np.nan

    # Duplicate a small number of rows verbatim (simulates a duplicate ingestion
    # event) so downstream dedup logic has something real to catch, and so the
    # generator's own leakage test below is checking something non-trivial.
    dup_idx = rng2.choice(len(df), size=int(len(df) * 0.005), replace=False)
    dup_rows = df.iloc[dup_idx].copy()
    dup_rows["case_id"] = dup_rows["case_id"] + "_dup"
    df = pd.concat([df, dup_rows], ignore_index=True)

    # Temporal split on obligation_created_at, same convention as ar_recovery_v1 /
    # billing_recovery_v3 (train earliest 70%, validation next 15%, test latest 15%).
    df = df.sort_values("obligation_created_at", kind="stable").reset_index(drop=True)
    n_total = len(df)
    split = np.empty(n_total, dtype=object)
    split[: int(n_total * 0.70)] = "train"
    split[int(n_total * 0.70) : int(n_total * 0.85)] = "validation"
    split[int(n_total * 0.85) :] = "test"
    df["split"] = split
    df["obligation_created_at"] = pd.to_datetime(df["obligation_created_at"]).dt.strftime(
        "%Y-%m-%d"
    )

    return df


