"""RecoverChain AI reconstruction (§4-14): a scientific, documented, seeded
generator for four of the six datasets the brief calls for:

  1. RecoverChain_Recovery_Outcome_Strong  — a GENUINE recovery target
     (P(recovered within a defined window | X)), which nothing else in this
     repo has: ar_recovery_v1 never has a true non-recovery (everything
     eventually settles) and billing_recovery_v3's target is a noisy
     per-cycle proxy (see docs/ai_reconstruction/02_SEMANTIC_TARGET_CLASSIFICATION.md).

  2. RecoverChain_Ethical_Edge_Cases — hand-specified scenarios (A-J from
     the brief) whose "expected_decision" is the REAL rule name the policy
     engine (backend/application/policy_engine.py) actually raises for that
     situation, not an invented expectation. Proven against production code
     in backend/tests/ml/test_ethical_edge_cases.py.

  3. RecoverChain_Action_Outcome_Strong — P(recovery | X, action), explicitly
     labeled OBSERVATIONAL_DATA: the action is assigned by a policy-like rule
     correlated with case features, so action and difficulty are confounded
     by construction, not hidden.

  4. RecoverChain_Guide_Demo — a compact, real-schema dataset meant to be
     uploaded through the live running app, not just inspected as a file.

Not built here: Payment Failure Strong and MultiDomain Strong (lower
marginal value — this repo's live /events ingestion and domain classifier
already exercise that shape; see docs/ai_reconstruction/REPOSITORY_FORENSIC_AUDIT.md).

Every label here is generated by a DOCUMENTED weighted-logistic mechanism
with injected noise, never a hard rule like `if X then target=Y`.  No
column equals or trivially determines the target. Fixed seed, recorded
below and in the manifest, for reproducibility.

Usage:
    venv/Scripts/python.exe scripts/data_generation/generate_recoverchain_datasets.py
"""

