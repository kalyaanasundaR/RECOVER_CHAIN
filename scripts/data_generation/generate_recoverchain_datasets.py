def generate_guide_demo(seed=SEED + 3):
    """A compact (150-row) dataset matching the LIVE APP's real ingestion
    schema (customer_id, amount, invoice_date, status, reason — same shape as
    the app's own built-in sample data) so it can actually be uploaded through
    the running RecoverChain UI, not just inspected as a file. `status` values
    are drawn from the app's real classification vocabulary
    (api/dataset_router.py's _NOT_FAILED / _FAILED sets) and `reason` values
    from the real diagnosis engine's recognized failure codes
    (application/diagnosis_engine.py) so every row produces a real, specific
    diagnosis and policy outcome rather than a generic one.

    Deliberately includes, by row count, examples that exercise every stage a
    guide would want to see:
      - already-paid rows (skipped at ingestion, never become cases)
      - small failed payments (auto-approved and executed)
      - large failed payments (escalate for human approval)
      - an exact duplicate pair (verified: within one upload the app treats
        this as two legitimate occurrences, not a dedup -- real dedup fires
        only when the SAME file is re-ingested; see DATASET_CATALOG.md)
      - each of the four recognized failure reasons
    """
    rng = np.random.default_rng(seed)
    rows = []

    def add(customer, amount, status, reason, days_ago):
        rows.append(
            {
                "customer_id": customer,
                "amount": round(amount, 2),
                "invoice_date": (
                    datetime(2026, 9, 1, tzinfo=UTC) - timedelta(days=days_ago)
                ).strftime("%Y-%m-%d"),
                "status": status,
                "reason": reason,
            }
        )

    # Already paid -- should be skipped at ingestion (not_at_risk), never a case.
    for i in range(20):
        add(
            f"guide_paid_{i}",
            rng.uniform(100, 5000),
            rng.choice(["paid", "success", "settled"]),
            "",
            int(rng.integers(1, 60)),
        )

    # Small failed payments -- auto-approvable under the 5000 threshold.
    for i in range(80):
        add(
            f"guide_small_{i}",
            rng.uniform(50, 4800),
            "failed",
            rng.choice(FAILURE_REASONS),
            int(rng.integers(0, 30)),
        )

    # Large failed payments -- above the automated threshold, should escalate.
    for i in range(30):
        add(
            f"guide_large_{i}",
            rng.uniform(5100, 60000),
            "failed",
            rng.choice(FAILURE_REASONS),
            int(rng.integers(0, 30)),
        )

    # One exact duplicate pair -- same customer/amount/date/reason, submitted twice.
    dup_row = dict(
        customer_id="guide_dup_customer",
        amount=2500.0,
        invoice_date="2026-08-15",
        status="failed",
        reason="network_error",
    )
    rows.append(dup_row)
    rows.append(dict(dup_row))

    # A handful of unpaid/declined variants, to exercise the rest of the vocabulary.
    for i in range(15):
        add(
            f"guide_variant_{i}",
            rng.uniform(200, 3000),
            rng.choice(["unpaid", "declined", "error"]),
            rng.choice(FAILURE_REASONS),
            int(rng.integers(0, 20)),
        )

    df = pd.DataFrame(rows)
    return df.sample(frac=1, random_state=seed).reset_index(
        drop=True
    )  # shuffle so stages aren't grouped


def validate_guide_demo(df: pd.DataFrame) -> list[str]:
    problems = []
    required = {"customer_id", "amount", "invoice_date", "status", "reason"}
    missing_cols = required - set(df.columns)
    if missing_cols:
        problems.append(f"SCHEMA: missing required columns {missing_cols}")
    if not (100 <= len(df) <= 300):
        problems.append(f"SIZE: {len(df)} rows, spec calls for 100-300")
    dup_rows = df.drop(columns=[]).duplicated().sum()
    if dup_rows < 1:
        problems.append(
            "CONTENT: expected at least one intentional exact-duplicate row (for the re-ingestion dedup demo -- see DATASET_CATALOG.md)"
        )
    return problems


# ---------------------------------------------------------------------------
# Validation — schema / leakage / distribution / entity / temporal checks.
# A dataset that fails these is not written as "ready"; the generator prints
# the failure and stops rather than silently shipping a bad dataset (§36).
# ---------------------------------------------------------------------------


def validate_recovery_outcome(df: pd.DataFrame) -> list[str]:
    problems = []
    required = {
        "case_id",
        "customer_id",
        "obligation_id",
        "domain",
        "amount_at_risk",
        "recovery_success",
        "split",
    }
    missing_cols = required - set(df.columns)
    if missing_cols:
        problems.append(f"SCHEMA: missing required columns {missing_cols}")

    if df["recovery_success"].nunique() < 2:
        problems.append("DISTRIBUTION: target has fewer than 2 classes")
    pos_rate = df["recovery_success"].mean()
    if not (0.05 < pos_rate < 0.95):
        problems.append(
            f"DISTRIBUTION: positive rate {pos_rate:.3f} is degenerate (too close to 0 or 1)"
        )

    # Leakage: no single feature should perfectly separate the label (a very
    # simple, honest proxy check -- correlation of 1.0 with any numeric column).
    numeric = df.select_dtypes(include="number").drop(columns=["recovery_success"], errors="ignore")
    corr = numeric.corrwith(df["recovery_success"]).abs()
    perfect = corr[corr > 0.98]
    if len(perfect):
        problems.append(f"LEAKAGE: near-perfect correlation with target: {perfect.to_dict()}")

    dup_ids = df["case_id"].duplicated().sum()
    if dup_ids:
        problems.append(
            f"ENTITY: {dup_ids} duplicate case_id values (unexpected outside the intentional _dup rows)"
        )

    # Real temporal-consistency check (added after the original generator's
    # bug was found: number_of_previous_recoveries used to be independent
    # per-row noise, so it could DECREASE across a customer's own later
    # obligations -- impossible for a genuine cumulative count). For every
    # customer, sorted by their own obligation date, both rolling counters
    # must be non-decreasing.
    non_dup = df[~df["case_id"].str.endswith("_dup")]
    bad_customers = []
    for cust_id, grp in non_dup.groupby("customer_id"):
        ordered = grp.sort_values("obligation_created_at")
        recov = ordered["number_of_previous_recoveries"].to_numpy()
        fail = ordered["number_of_previous_failed_attempts"].to_numpy()
        if (pd.Series(recov).diff().dropna() < 0).any() or (
            pd.Series(fail).diff().dropna() < 0
        ).any():
            bad_customers.append(cust_id)
    if bad_customers:
        problems.append(
            f"TEMPORAL_LEAKAGE: {len(bad_customers)} customers have a non-monotonic "
            f"rolling history count (e.g. {bad_customers[:3]}) -- prior_* features "
            "must be true cumulative statistics, not independent per-row noise"
        )

    return problems


def validate_ethical_edge_cases(df: pd.DataFrame) -> list[str]:
    problems = []
    required = {"case_id", "scenario", "amount_at_risk", "expected_decision"}
    missing_cols = required - set(df.columns)
    if missing_cols:
        problems.append(f"SCHEMA: missing required columns {missing_cols}")
    if df["case_id"].duplicated().any():
        problems.append("ENTITY: duplicate case_id in ethical edge cases")
    if df["expected_decision"].isna().any():
        problems.append("SCHEMA: every edge case must have an expected_decision")
    return problems


# ---------------------------------------------------------------------------
# Write outputs + manifest
# ---------------------------------------------------------------------------


def _write(
    df: pd.DataFrame,
    name: str,
    target: str | None,
    description: str,
    problems: list[str],
    intended_use: str = "RESEARCH / TRAINING (synthetic, not production data)",
):
    subdir = OUT_DIR / name
    subdir.mkdir(parents=True, exist_ok=True)
    xlsx_path = subdir / f"{name}.xlsx"
    csv_path = subdir / f"{name}.csv"
    df.to_excel(xlsx_path, index=False, engine="openpyxl")
    df.to_csv(csv_path, index=False)

    manifest = {
        "dataset_id": name,
        "dataset_version": "v1",
        "generation_timestamp": datetime.now(UTC).isoformat(),
        "random_seed": SEED,
        "row_count": len(df),
        "column_count": len(df.columns),
        "columns": list(df.columns),
        "target_column": target,
        "description": description,
        "xlsx_checksum_sha256": _checksum(xlsx_path),
        "csv_checksum_sha256": _checksum(csv_path),
        "validation_problems": problems,
        "validation_status": "PASSED" if not problems else "FAILED",
        "intended_use": intended_use,
    }
    if target and target in df.columns and pd.api.types.is_numeric_dtype(df[target]):
        manifest["positive_class_rate"] = float(df[target].mean())
    if "split" in df.columns:
        manifest["split_counts"] = df["split"].value_counts().to_dict()

    manifest_path = MANIFEST_DIR / f"{name}_manifest.json"
    with open(manifest_path, "w") as f:
        json.dump(manifest, f, indent=2, default=str)

    print(f"[{name}] rows={len(df)} cols={len(df.columns)} -> {xlsx_path}")
    if problems:
        print(f"[{name}] VALIDATION FAILED: {problems}")
    else:
        print(f"[{name}] validation passed")
    return manifest


def main():
    print(f"RecoverChain synthetic dataset generator — seed={SEED}")

    recovery_df = generate_recovery_outcome()
    recovery_problems = validate_recovery_outcome(recovery_df)
